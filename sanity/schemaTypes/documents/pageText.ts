import { defineField, defineType } from "sanity";

/**
 * Singleton with the fixed text on the inner pages, the enquiry form and its messages.
 * Some lines take a name that changes per page; write it as a placeholder in braces and
 * the site fills it in, e.g. "Talk to {division}" becomes "Talk to JHM Geo Consult".
 */

